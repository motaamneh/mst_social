package com.motaamneh.mstsocial.server.persistence;

import com.motaamneh.mstsocial.server.security.TenantApiKey;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.jdbc.core.namedparam.MapSqlParameterSource;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.stereotype.Repository;

import javax.sql.DataSource;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Types;
import java.time.Instant;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.UUID;

@Repository
public class TenantApiKeyRepository {
    private final NamedParameterJdbcTemplate jdbcTemplate;

    public TenantApiKeyRepository(DataSource dataSource) {
        this.jdbcTemplate = new NamedParameterJdbcTemplate(
                Objects.requireNonNull(dataSource, "dataSource must not be null")
        );
    }

    /** Authentication lookup: the credential establishes the tenant after secret validation. */
    public Optional<TenantApiKey> findById(UUID id) {
        Objects.requireNonNull(id, "id must not be null");
        List<TenantApiKey> keys = jdbcTemplate.query("""
                SELECT id, tenant_id, name, secret_digest, created_at, expires_at, revoked_at
                FROM tenant_api_keys
                WHERE id = :id
                """, new MapSqlParameterSource("id", id), ROW_MAPPER);
        return keys.stream().findFirst();
    }

    /** Inserts a credential with the ID generated by the provisioning service. */
    public void insert(TenantApiKey apiKey) {
        Objects.requireNonNull(apiKey, "apiKey must not be null");
        MapSqlParameterSource parameters = new MapSqlParameterSource()
                .addValue("id", apiKey.getId())
                .addValue("tenantId", apiKey.getTenantId())
                .addValue("name", apiKey.getName())
                .addValue("secretDigest", apiKey.getSecretDigest());
        addInstant(parameters, "createdAt", apiKey.getCreatedAt());
        addInstant(parameters, "expiresAt", apiKey.getExpiresAt());
        addInstant(parameters, "revokedAt", apiKey.getRevokedAt());

        int inserted = jdbcTemplate.update("""
                INSERT INTO tenant_api_keys
                    (id, tenant_id, name, secret_digest, created_at, expires_at, revoked_at)
                VALUES
                    (:id, :tenantId, :name, :secretDigest, :createdAt, :expiresAt, :revokedAt)
                """, parameters);
        if (inserted != 1) {
            throw new IllegalStateException("Expected one inserted tenant API key");
        }
    }

    /**
     * Returns true only when this call records revocation. Returns false for missing,
     * other-tenant, already revoked, or not-yet-created credentials.
     * Repeated calls preserve the original timestamp, including under concurrency.
     */
    public boolean revoke(UUID tenantId, UUID credentialId, Instant now) {
        Objects.requireNonNull(tenantId, "tenantId must not be null");
        Objects.requireNonNull(credentialId, "credentialId must not be null");
        Objects.requireNonNull(now, "now must not be null");
        MapSqlParameterSource parameters = new MapSqlParameterSource("tenantId", tenantId)
                .addValue("id", credentialId);
        addInstant(parameters, "now", now);
        return jdbcTemplate.update("""
                UPDATE tenant_api_keys
                SET revoked_at = :now
                WHERE tenant_id = :tenantId AND id = :id
                  AND revoked_at IS NULL AND created_at <= :now
                """, parameters) == 1;
    }

    private static void addInstant(MapSqlParameterSource parameters, String name, Instant value) {
        parameters.addValue(name, value == null ? null : value.atOffset(ZoneOffset.UTC),
                Types.TIMESTAMP_WITH_TIMEZONE);
    }

    private static Instant instant(ResultSet resultSet, String column) throws SQLException {
        OffsetDateTime value = resultSet.getObject(column, OffsetDateTime.class);
        return value == null ? null : value.toInstant();
    }

    private static final RowMapper<TenantApiKey> ROW_MAPPER = (resultSet, rowNumber) ->
            new TenantApiKey(
                    resultSet.getObject("id", UUID.class),
                    resultSet.getObject("tenant_id", UUID.class),
                    resultSet.getString("name"),
                    resultSet.getBytes("secret_digest"),
                    instant(resultSet, "created_at"),
                    instant(resultSet, "expires_at"),
                    instant(resultSet, "revoked_at")
            );
}
